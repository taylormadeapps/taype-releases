#!/usr/bin/env python3
"""Render the shared community section; update/check the company page's copy."""

import argparse
import html
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TOKEN = re.compile(r"\{\{([a-zA-Z0-9_.]+)\}\}")
START = "    <!-- community:start (generated by scripts/render_community.py) -->"
END = "    <!-- community:end -->"


def render() -> str:
    catalogue = json.loads((ROOT / "locales/community.en-GB.json").read_text(encoding="utf-8"))
    template = (ROOT / "templates/community.html").read_text(encoding="utf-8")
    if not all(isinstance(value, str) and value for value in catalogue.values()):
        raise ValueError("Every community source-locale entry must be a nonempty string")
    keys = set(TOKEN.findall(template))
    missing = keys - catalogue.keys()
    unused = catalogue.keys() - keys
    if missing or unused:
        raise ValueError(f"Community catalogue mismatch: missing={sorted(missing)}, unused={sorted(unused)}")
    if catalogue["follow.body"].count("{company}") != 1:
        raise ValueError("Community follow.body must contain exactly one {company} placeholder")
    values = {key: html.escape(value, quote=True) for key, value in catalogue.items()}
    values["follow.body"] = values["follow.body"].replace(
        "{company}", '<a href="/ruminant-audio-works/">Ruminant Audio Works</a>'
    )
    rendered = TOKEN.sub(lambda match: values[match[1]], template)
    if "{{" in rendered or "}}" in rendered:
        raise ValueError("Unresolved community template token")
    return rendered


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Refuse stale generated HTML without writing")
    args = parser.parse_args()
    page = ROOT / "ruminant-audio-works/index.html"
    source = page.read_text(encoding="utf-8")
    if source.count(START) != 1 or source.count(END) != 1 or source.index(START) > source.index(END):
        raise ValueError("Company page must contain exactly one ordered community marker pair")
    before, rest = source.split(START)
    _, after = rest.split(END)
    rendered = before + START + "\n" + render() + END + after
    if args.check:
        if source != rendered:
            raise SystemExit("Company community section is stale; run scripts/render_community.py")
        print("Company community HTML matches its shared template and catalogue")
    else:
        page.write_text(rendered, encoding="utf-8")
        print(f"Rendered community section in {page}")


if __name__ == "__main__":
    main()
