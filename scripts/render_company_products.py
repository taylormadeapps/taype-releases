#!/usr/bin/env python3
"""Render or verify company product cards and the account label from the source locale."""

import argparse
import html
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TOKEN = re.compile(r"\{\{([a-zA-Z0-9_.]+)\}\}")
START = "    <!-- company-products:start (generated by scripts/render_company_products.py) -->"
END = "    <!-- company-products:end -->"
ACCOUNT = re.compile(r"(<!-- company:nav\.account -->).*?(<!-- /company -->)", re.DOTALL)


def render(source: str) -> str:
    catalogue = json.loads((ROOT / "locales/company.en-GB.json").read_text(encoding="utf-8"))
    template = (ROOT / "templates/company-products.html").read_text(encoding="utf-8")
    keys = set(TOKEN.findall(template)) | {"nav.account"}
    missing = keys - catalogue.keys()
    unused = catalogue.keys() - keys
    if missing or unused:
        raise ValueError(f"Company catalogue mismatch: missing={sorted(missing)}, unused={sorted(unused)}")
    if not all(isinstance(value, str) and value.strip() for value in catalogue.values()):
        raise ValueError("Every company source-locale entry must be a nonempty string")
    if source.count(START) != 1 or source.count(END) != 1 or source.index(START) > source.index(END):
        raise ValueError("Company page must contain exactly one ordered company-products marker pair")
    if len(ACCOUNT.findall(source)) != 1:
        raise ValueError("Company page must contain exactly one account label marker pair")

    values = {key: html.escape(value, quote=True) for key, value in catalogue.items()}
    products = TOKEN.sub(lambda match: values[match[1]], template)
    if "{{" in products or "}}" in products:
        raise ValueError("Unresolved company product template token")
    before, rest = source.split(START)
    _, after = rest.split(END)
    combined = before + START + "\n" + products + END + after
    return ACCOUNT.sub(lambda match: match[1] + values["nav.account"] + match[2], combined)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Refuse stale generated HTML without writing")
    args = parser.parse_args()
    page = ROOT / "ruminant-audio-works/index.html"
    source = page.read_text(encoding="utf-8")
    rendered = render(source)
    if args.check:
        if source != rendered:
            raise SystemExit("Company product section or account label is stale; run scripts/render_company_products.py")
        print("Company product section and account label match their template and catalogue")
    else:
        page.write_text(rendered, encoding="utf-8")
        print(f"Rendered company products and account label in {page}")


if __name__ == "__main__":
    main()
